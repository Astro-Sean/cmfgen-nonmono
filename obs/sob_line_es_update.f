C
C Recompute the stored continuum radiation field after resolved
C Sobolev line opacity/emissivity has been deposited in ETA_ST/CHI_ST.
C The normal CMF_FLUX electron-scattering pass runs before those lines
C exist, so the line photons would otherwise enter OBS_FRAME without
C the non-coherent electron-scattering redistribution used for the
C continuum.  This routine repeats the formal-J/Lambda step on the
C line-containing opacity grid and rebuilds the scattering emissivity
C once, leaving the deposition arrays themselves unchanged.
C
	SUBROUTINE SOB_LINE_ES_UPDATE(ETA_ST,CHI_ST,RJ_ST,RJ_ES_ST,
     1	    IB_J_ST,IB_H_ST,RAY_ST,DUST_ST,ESEC,CLUMP_FAC,NU,T,DTDR,
     2	    COEF,INDX,POS_IN_NEW_GRID,REXT,PEXT,VEXT,TEXT,SIGMAEXT,
     3	    VDOP_VEC_EXT,AQWEXT,HQWEXT,KQWEXT,NQWEXT,HMIDQWEXT,
     4	    NMIDQWEXT,ND,NCF,NDEXT,NCEXT,NPEXT,NUM_ES,
     5	    INCL_RAY,INCL_DUST,COHERENT_ES,ACCURATE,DIF,RDTHK_CONT,SN_MODEL,
     6	    THK_EDGE_FREQ,FIX_NEG_DBB,IC,REXT_FAC,DELV_FRAC_FG,
     7	    METHOD,FG_SOL_OPTIONS,LUER,EDD_CONT_REC,MAX_CHG)
	USE SET_KIND_MODULE
	IMPLICIT NONE
C
	INTEGER ND,NCF,NDEXT,NCEXT,NPEXT,NUM_ES,LUER,EDD_CONT_REC
	INTEGER INDX(NDEXT),POS_IN_NEW_GRID(ND)
	REAL(KIND=LDP) ETA_ST(ND,NCF),CHI_ST(ND,NCF)
	REAL(KIND=LDP) RJ_ST(ND,NCF),RJ_ES_ST(ND,NCF)
	REAL(KIND=LDP) IB_J_ST(NCF),IB_H_ST(NCF)
	REAL(KIND=LDP) RAY_ST(ND,NCF),DUST_ST(ND,NCF)
	REAL(KIND=LDP) ESEC(ND),CLUMP_FAC(ND)
	REAL(KIND=LDP) NU(NCF),T(ND),DTDR
	REAL(KIND=LDP) COEF(0:3,NDEXT)
	REAL(KIND=LDP) REXT(NDEXT),PEXT(NPEXT),VEXT(NDEXT)
	REAL(KIND=LDP) TEXT(NDEXT),SIGMAEXT(NDEXT)
	REAL(KIND=LDP) VDOP_VEC_EXT(NDEXT)
	REAL(KIND=LDP) AQWEXT(NDEXT,NPEXT),HQWEXT(NDEXT,NPEXT)
	REAL(KIND=LDP) KQWEXT(NDEXT,NPEXT),NQWEXT(NDEXT,NPEXT)
	REAL(KIND=LDP) HMIDQWEXT(NDEXT,NPEXT),NMIDQWEXT(NDEXT,NPEXT)
	REAL(KIND=LDP) THK_EDGE_FREQ,IC,REXT_FAC,DELV_FRAC_FG
	REAL(KIND=LDP) MAX_CHG
	LOGICAL INCL_RAY,INCL_DUST,COHERENT_ES,ACCURATE,DIF,RDTHK_CONT
	LOGICAL SN_MODEL,FIX_NEG_DBB
	CHARACTER*6 METHOD
	CHARACTER*10 FG_SOL_OPTIONS
C
	REAL(KIND=LDP), ALLOCATABLE :: ETA_FIXED(:,:)
	REAL(KIND=LDP), ALLOCATABLE :: ETAEXT(:),CHIEXT(:),ESECEXT(:)
	REAL(KIND=LDP), ALLOCATABLE :: RAYEXT(:),DUSTEXT(:),SCATEXT(:)
	REAL(KIND=LDP), ALLOCATABLE :: RJEXT(:),RJEXT_ES(:)
	REAL(KIND=LDP), ALLOCATABLE :: ETA_SRC(:),JEXT(:),RJ(:)
	REAL(KIND=LDP), ALLOCATABLE :: FEDD(:),IPLUS(:)
	REAL(KIND=LDP), ALLOCATABLE :: ESEC_CLUMP(:)
	REAL(KIND=LDP), ALLOCATABLE :: RJ_OLD(:)
C
	INTEGER IES,ML,I,IOS
	REAL(KIND=LDP) FL,DLOG_NU,DBB,BNUE,EMH,T1,T2
	REAL(KIND=LDP) RETURNED_IN_HBC,RETURNED_OUT_HBC
	LOGICAL FIRST_FREQ,THK_CONT
C
	COMMON/CONSTANTS/ CHIBF,CHIFF,HDKT,TWOHCSQ
	REAL(KIND=LDP) CHIBF,CHIFF,HDKT,TWOHCSQ
C
	ALLOCATE(ETA_FIXED(ND,NCF),STAT=IOS)
	IF(IOS .EQ. 0)ALLOCATE(ETAEXT(NDEXT),CHIEXT(NDEXT),
     1	    ESECEXT(NDEXT),RAYEXT(NDEXT),DUSTEXT(NDEXT),
     2	    SCATEXT(NDEXT),RJEXT(NDEXT),RJEXT_ES(NDEXT),
     3	    ETA_SRC(NDEXT),JEXT(NDEXT),RJ(ND),FEDD(NDEXT),
     4	    IPLUS(NPEXT),ESEC_CLUMP(ND),RJ_OLD(ND),STAT=IOS)
	IF(IOS .NE. 0)THEN
	  WRITE(LUER,*)'Error allocating arrays in SOB_LINE_ES_UPDATE'
	  WRITE(LUER,*)'STATUS=',IOS
	  STOP
	END IF
C
	ESEC_CLUMP(:)=ESEC(:)*CLUMP_FAC(:)
	IF(NUM_ES .LT. 1)THEN
	  WRITE(LUER,*)'Error in SOB_LINE_ES_UPDATE'
	  WRITE(LUER,*)'NUM_ES must be at least 1; got ',NUM_ES
	  STOP
	END IF
C
C ETA_ST contains the old continuum scattering source and the newly
C deposited line source.  Remove the old scattering terms once so the
C formal solve can replace them with sources evaluated from the
C line-containing radiation field.
C
	DO ML=1,NCF
	  ETA_FIXED(:,ML)=ETA_ST(:,ML)-RJ_ES_ST(:,ML)*ESEC_CLUMP(:)
	  IF(INCL_RAY)THEN
	    ETA_FIXED(:,ML)=ETA_FIXED(:,ML)-
     1	      RJ_ST(:,ML)*RAY_ST(:,ML)*CLUMP_FAC(:)
	  END IF
	  IF(INCL_DUST)THEN
	    ETA_FIXED(:,ML)=ETA_FIXED(:,ML)-
     1	      RJ_ST(:,ML)*DUST_ST(:,ML)*CLUMP_FAC(:)
	  END IF
	END DO
	IF(MINVAL(ETA_FIXED) .LE. 0.0_LDP .OR.
     1	    MINVAL(CHI_ST) .LE. 0.0_LDP .OR.
     2	    MINVAL(RJ_ST) .LE. 0.0_LDP .OR.
     3	    MINVAL(RJ_ES_ST) .LE. 0.0_LDP)THEN
	  WRITE(LUER,*)'Error in SOB_LINE_ES_UPDATE'
	  WRITE(LUER,*)'ETA, CHI, J and J_ES must be positive'
	  WRITE(LUER,*)'minima=',MINVAL(ETA_FIXED),MINVAL(CHI_ST),
     1	    MINVAL(RJ_ST),MINVAL(RJ_ES_ST)
	  STOP
	END IF
C
	DO IES=1,NUM_ES
	  MAX_CHG=0.0_LDP
	  DO ML=1,NCF
	    FL=NU(ML)
	    FIRST_FREQ=(ML .EQ. 1)
	    IF(FIRST_FREQ)THEN
	      DLOG_NU=0.0_LDP
	    ELSE
	      DLOG_NU=LOG(NU(ML-1)/NU(ML))
	    END IF
C
	    EMH=EXP(-HDKT*FL/T(ND))
	    T1=HDKT*FL/T(ND)
	    T2=1.0_LDP-EMH
	    BNUE=TWOHCSQ*(FL**3)*EMH/T2
	    DBB=TWOHCSQ*(FL**3)*T1*DTDR/T(ND)*EMH/(T2**2)
	    IF(FIX_NEG_DBB .AND. DBB .LT. 0.0_LDP)DBB=1.0D-99
	    IF(SN_MODEL .AND. .NOT. DIF)THEN
	      BNUE=0.0_LDP
	      DBB=0.0_LDP
	    END IF
	    THK_CONT=(RDTHK_CONT .AND. FL .GT. THK_EDGE_FREQ)
C
	    IF(ACCURATE)THEN
	      CALL EXTEND3OPAC(CHIEXT,ETAEXT,ESECEXT,COEF,INDX,NDEXT,
     1	          CHI_ST(1,ML),ETA_FIXED(1,ML),ESEC_CLUMP,ND)
	      CALL EXTEND3OPAC(RJEXT,RJEXT_ES,SCATEXT,COEF,INDX,NDEXT,
     1	          RJ_ST(1,ML),RJ_ES_ST(1,ML),ESEC_CLUMP,ND)
	    ELSE
	      CHIEXT(:)=CHI_ST(:,ML)
	      ETAEXT(:)=ETA_FIXED(:,ML)
	      ESECEXT(:)=ESEC_CLUMP(:)
	      RJEXT(:)=RJ_ST(:,ML)
	      RJEXT_ES(:)=RJ_ES_ST(:,ML)
	    END IF
C
	    RAYEXT(:)=0.0_LDP
	    DUSTEXT(:)=0.0_LDP
	    IF(INCL_RAY)THEN
	      ETA_SRC(1:ND)=RAY_ST(:,ML)*CLUMP_FAC(:)
	      IF(ACCURATE)THEN
	        CALL EXTEND3OPAC(RAYEXT,FEDD,JEXT,COEF,INDX,NDEXT,
     1	            ETA_SRC,ESEC_CLUMP,ESEC_CLUMP,ND)
	      ELSE
	        RAYEXT(:)=ETA_SRC(:)
	      END IF
	    END IF
	    IF(INCL_DUST)THEN
	      ETA_SRC(1:ND)=DUST_ST(:,ML)*CLUMP_FAC(:)
	      IF(ACCURATE)THEN
	        CALL EXTEND3OPAC(DUSTEXT,FEDD,JEXT,COEF,INDX,NDEXT,
     1	            ETA_SRC,ESEC_CLUMP,ESEC_CLUMP,ND)
	      ELSE
	        DUSTEXT(:)=ETA_SRC(:)
	      END IF
	    END IF
	    SCATEXT(:)=ESECEXT(:)+RAYEXT(:)+DUSTEXT(:)
	    IF(COHERENT_ES)THEN
	      ETA_SRC(:)=ETAEXT(:)+SCATEXT(:)*RJEXT(:)
	    ELSE
	      ETA_SRC(:)=ETAEXT(:)+ESECEXT(:)*RJEXT_ES(:)+
     1	        (RAYEXT(:)+DUSTEXT(:))*RJEXT(:)
	    END IF
C
	    RJ_OLD(:)=RJ_ST(:,ML)
	    CALL FG_J_CMF_V12(ETA_SRC,CHIEXT,SCATEXT,VEXT,SIGMAEXT,
     1	        REXT,PEXT,JEXT,FEDD,AQWEXT,HQWEXT,KQWEXT,NQWEXT,
     2	        HMIDQWEXT,NMIDQWEXT,RETURNED_IN_HBC,
     3	        RETURNED_OUT_HBC,IPLUS,FL,DLOG_NU,DIF,DBB,IC,
     4	        VDOP_VEC_EXT,DELV_FRAC_FG,REXT_FAC,METHOD,
     5	        FG_SOL_OPTIONS,THK_CONT,FIRST_FREQ,.TRUE.,
     6	        NCEXT,NPEXT,NDEXT)
	    IF(ACCURATE)THEN
	      CALL UNGRID(RJ,ND,JEXT,NDEXT,POS_IN_NEW_GRID)
	    ELSE
	      RJ(:)=JEXT(1:ND)
	    END IF
	    DO I=1,ND
	      T1=ABS(RJ(I)-RJ_OLD(I))/MAX(ABS(RJ_OLD(I)),1.0D-99)
	      IF(T1 .GT. MAX_CHG)MAX_CHG=T1
	    END DO
	    RJ_ST(:,ML)=RJ(:)
	    IB_J_ST(ML)=RJ(ND)
	    IF(DIF)THEN
	      IF(CHI_ST(ND,ML) .LE. 0.0_LDP .OR.
     1	          CLUMP_FAC(ND) .LE. 0.0_LDP)THEN
	        WRITE(LUER,*)'Error in SOB_LINE_ES_UPDATE'
	        WRITE(LUER,*)'Invalid inner-boundary opacity or clumping'
	        STOP
	      END IF
	      IB_H_ST(ML)=DBB*CLUMP_FAC(ND)/(3.0_LDP*CHI_ST(ND,ML))
	    END IF
	  END DO
C
	  RJ_ES_ST(:,:)=RJ_ST(:,:)
	  IF(.NOT. COHERENT_ES)THEN
	    I=ND*NCF
	    CALL COMP_J_CONV_V2(RJ_ES_ST,I,NU,T,ND,NCF,
     1	      LUER,'J PASSED VIA CALL',EDD_CONT_REC,.FALSE.,.FALSE.,
     2	      LUER,'RETURN J VIA CALL')
	  END IF
	  WRITE(LUER,'(A,1X,I3,1X,A,1P,E12.4)')
     1	    'SOB_LINE_ES iteration',IES,'maximum relative dJ=',MAX_CHG
	END DO
C
	DO ML=1,NCF
	  ETA_ST(:,ML)=ETA_FIXED(:,ML)+RJ_ES_ST(:,ML)*ESEC_CLUMP(:)
	  IF(INCL_RAY)THEN
	    ETA_ST(:,ML)=ETA_ST(:,ML)+
     1	      RJ_ST(:,ML)*RAY_ST(:,ML)*CLUMP_FAC(:)
	  END IF
	  IF(INCL_DUST)THEN
	    ETA_ST(:,ML)=ETA_ST(:,ML)+
     1	      RJ_ST(:,ML)*DUST_ST(:,ML)*CLUMP_FAC(:)
	  END IF
	END DO
C
	RETURN
	END
