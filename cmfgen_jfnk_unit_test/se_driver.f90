! se_driver: CLI driver for cmfgen_jfnk unit tests.  Calls the
! production newton_hook_v1 / gmres_m_v1 (new_main/mod_subs/
! jfnk_solver_v1.f90) on the surrogate SE systems generated by
! gen_se_system.py.
!
! Commands:
!   sef      <dir> [xfile]                       F(x) per row + norms
!   sejvp    <dir> <vfile> <eps>                 FD vs exact J*v
!   sestats  <dir>                               J0/F anatomy + demanded step
!   sepc     <dir> <pc> <expneg> <ptc> <ptcfix> <xfile>
!                                              factor + apply M^-1 to F(x)
!   segmres  <dir> <m> <itmax> <pc> <eps> <expneg> <ptc> <ptcfix>
!                                              production GMRES on J s = F(0)
!   senewton <dir> <m> <nits> <pc> <eps> <rowtiny> <ridge> <expneg>
!            <ptc> <ptcfix> <eqscale> <cap> <gtolfac>
!                                              production newton_hook_v1
!   sestrike <dir> <rearm_every> <seq>
!                                              strike/cooldown FSM
!            replica of JFNK_SOLVE_CORR_V1; seq chars per admitted
!            call: F = LU admission (fails), S = LSQ-alg admission
!            (commits on hard), R = reach-gate skip (not counted)
!
! pc: 0=identity 1=jacobi 2=depth-block LU replica
program se_driver
   use se_prob_mod
   use jfnk_solver_v1_mod
   implicit none
   character(len=32) :: cmd, arg
   character(len=64) :: seqstr
   character(len=1024) :: dir, xfile, vfile
   integer :: n, m, itmax, pc, expneg, ptc, ptcfix, eqscale
   integer :: k, i, idx, info, its, lu, nits, stat, im(10), kk, ios
   integer :: stag, cool, cyc, wait_i, rearm_every
   integer :: ta_nlock, rung, ncom
   logical :: disarm
   double precision :: eps, rowtiny, ridge, cap, gtolfac
   double precision :: re0, re_n, eps_t, alpha_l, pert
   double precision :: res, del, pred_res, f0nrm, vals(10)
   double precision, allocatable :: x(:), f(:), v(:), jv1(:), jv2(:)
   double precision, allocatable :: h(:,:), vv(:,:), z(:), mz(:), s(:)
   double precision :: gtol, tol, mndl, mxdl
   double precision :: gtmp, rr
   logical :: reach_ok
   external :: se_f, se_jvp_fd, se_psolve, se_psolve_jacobi, &
               se_psolve_ident, se_psolve_tsvd, se_psolve_ptclu, &
               se_psolve_lsq, se_psolve_lsq2, se_psolve_schur, se_sub
   double precision, external :: se_dp

   call get_command_argument(1, cmd)

   select case (trim(cmd))

   case ('sef')
      call get_command_argument(2, dir)
      call get_command_argument(3, xfile)
      call se_load(dir, stat)
      if (stat /= 0) stop 2
      n = se_n
      allocate(x(n), f(n))
      x = 0d0
      if (len_trim(xfile) > 0 .and. trim(xfile) /= '0') then
         open(newunit=lu, file=trim(xfile), status='old')
         read(lu, *) x
         close(lu)
      end if
      jfnk_x = x
      jfnk_ptc_active = .false.
      call get_command_argument(4, arg)
      se_tauto_on = (len_trim(arg) > 0)
      call se_f_raw(n, x, f)
      write(*, '(A,ES24.16)') 'FNORM ', sqrt(sum(f*f))
      write(*, '(A,ES24.16)') 'FINF  ', maxval(abs(f))
      do i = 1, n
         write(*, '(A,I0,1X,ES24.16)') 'F ', i, f(i)
      end do

   case ('sejvp')
      call get_command_argument(2, dir)
      call get_command_argument(3, vfile)
      call get_command_argument(4, arg); read(arg, *) eps
      call get_command_argument(5, xfile)
      arg = ''
      call get_command_argument(6, arg, status=ios)
      call se_load(dir, stat)
      if (ios == 0 .and. len_trim(arg) > 0) then
         read(arg, *) expneg
         se_tauto_on = (expneg /= 0)
      else
         se_tauto_on = .false.
      end if
      n = se_n
      allocate(x(n), v(n), jv1(n), jv2(n), f(n))
      x = 0d0
      if (len_trim(xfile) > 0 .and. trim(xfile) /= '0') then
         open(newunit=lu, file=trim(xfile), status='old')
         read(lu, *) x
         close(lu)
      end if
      open(newunit=lu, file=trim(vfile), status='old')
      read(lu, *) v
      close(lu)
      jfnk_x = x
      jfnk_ptc_active = .false.
      se_eps = eps
      call se_jvp_fd(n, v, jv1)
      call se_jexact(n, x, v, jv2)
      write(*, '(A,ES24.16)') 'JVFDNORM ', sqrt(sum(jv1*jv1))
      write(*, '(A,ES24.16)') 'JVEXNORM ', sqrt(sum(jv2*jv2))
      write(*, '(A,ES24.16)') 'DIFFNORM ', sqrt(sum((jv1-jv2)**2))
      write(*, '(A,ES24.16)') 'RELDIFF  ', &
         sqrt(sum((jv1-jv2)**2)) / max(sqrt(sum(jv2*jv2)), 1d-300)
      do i = 1, n
         write(*, '(A,I0,1X,2(ES24.16,1X))') 'JV ', i, jv1(i), jv2(i)
      end do

   case ('sestats')
      call get_command_argument(2, dir)
      call se_load(dir, stat)
      n = se_n
      allocate(x(n), f(n), s(n))
      x = 0d0
      call se_f_raw(n, x, f)
      call se_factor_lu()
      write(*, '(A,ES24.16)') 'FNORM0 ', sqrt(sum(f*f))
      write(*, '(A,ES24.16)') 'FINF0  ', maxval(abs(f))
      write(*, '(A,I0)')       'NREG   ', se_nreg
      write(*, '(A,I0)')       'NRIDGE ', se_nridge_depths
      do k = 1, se_nd
         write(*, '(A,I0,1X,ES24.16)') 'BLKMAX ', k, &
            maxval(abs(m0_blk(:,:,k)))
      end do
      ! demanded exact Newton step: dense LU of J0
      block
         double precision, allocatable :: j0(:,:)
         integer, allocatable :: ipiv(:)
         allocate(j0(n,n), ipiv(n))
         do i = 1, n
            j0(i,:) = a_se(i,:) * n0_se(:) + c_se(i,:)
         end do
         s = f
         call dgesv(n, 1, j0, n, ipiv, s, n, info)
         write(*, '(A,I0)')       'DGESV  ', info
         write(*, '(A,ES24.16)') 'SINF   ', maxval(abs(s))
         write(*, '(A,ES24.16)') 'SNRM   ', sqrt(sum(s*s))
         do i = 1, 10
            im(i) = i
            vals(i) = abs(s(i))
         end do
         ! top-10 |s| indices (selection)
         do i = 1, n
            if (any(im == i)) cycle
            kk = minloc(vals, 1)
            if (abs(s(i)) > vals(kk)) then
               vals(kk) = abs(s(i))
               im(kk) = i
            end if
         end do
         do i = 1, 10
            write(*, '(A,I0,1X,ES24.16)') 'STOP ', im(i), s(im(i))
         end do
         deallocate(j0, ipiv)
      end block

   case ('sepc')
      call get_command_argument(2, dir)
      call get_command_argument(3, arg); read(arg, *) pc
      call get_command_argument(4, arg); read(arg, *) expneg
      call get_command_argument(5, arg); read(arg, *) ptc
      call get_command_argument(6, arg); read(arg, *) ptcfix
      call get_command_argument(7, xfile)
      call se_load(dir, stat)
      n = se_n
      allocate(x(n), f(n), z(n), mz(n), s(n))
      x = 0d0
      if (len_trim(xfile) > 0 .and. trim(xfile) /= '0') then
         open(newunit=lu, file=trim(xfile), status='old')
         read(lu, *) x
         close(lu)
      end if
      jfnk_x = x
      se_expneg = (expneg == 1)
      se_ptcfix = (ptcfix == 1)
      jfnk_ptc_active = (ptc == 1)
      call se_f_raw(n, x, f)
      if (jfnk_ptc_active) call se_arm_ptc(n, f)
      call se_factor_lu()
      ! core solve only (production stages 1-4): verify M z_core = v
      z = f
      do k = 1, se_nd
         if (lu_ok(k)) then
            do i = 1, se_nt
               idx = (k-1)*se_nt + i
               z(idx) = z(idx) * row_sf(i,k)
            end do
            call dgetrs('N', se_nt, 1, lu_fac(1,1,k), se_nt, &
                        lu_ipiv(1,k), z((k-1)*se_nt+1), se_nt, info)
            do i = 1, se_nt
               idx = (k-1)*se_nt + i
               z(idx) = z(idx) * col_sf(i,k)
            end do
         end if
      end do
      mz = 0d0
      do k = 1, se_nd
         if (lu_ok(k)) then
            mz((k-1)*se_nt+1:k*se_nt) = matmul(m0_blk(:,:,k), &
                 z((k-1)*se_nt+1:k*se_nt))
         end if
      end do
      write(*, '(A,ES24.16)') 'MZDIFF ', &
         sqrt(sum((mz-f)**2)) / max(sqrt(sum(f*f)), 1d-300)
      ! reg-row projection then full pipeline via se_psolve for
      ! the post-stage comparison
      do k = 1, se_nd
         do i = 1, se_nt
            idx = (k-1)*se_nt + i
            if (row_reg(i,k)) z(idx) = 0d0
         end do
      end do
      s = z        ! core output for comparison with full pipeline
      z = f
      if (pc == 1) then
         call se_psolve_jacobi(n, z)
      else
         call se_psolve(n, z)
      end if
      write(*, '(A,ES24.16)') 'VNORM  ', sqrt(sum(f*f))
      write(*, '(A,ES24.16)') 'ZNORM  ', sqrt(sum(z*z))
      write(*, '(A,ES24.16)') 'ZINF   ', maxval(abs(z))
      write(*, '(A,ES24.16)') 'ZCORE  ', sqrt(sum((z-s)**2)) / &
         max(sqrt(sum(s*s)), 1d-300)
      do i = 1, n
         write(*, '(A,I0,1X,3(ES24.16,1X))') 'Z ', i, z(i), s(i), f(i)
      end do

   case ('lsqchk')
      ! apply lsq (direct m0_blk normal equations) and lsq2
      ! (algebraic B^T w from the raw block) to F; report the
      ! relative difference -- validates the formula that the
      ! production apply will use before the interface edit lands
      call get_command_argument(2, dir)
      call get_command_argument(3, arg); read(arg, *) eps
      call get_command_argument(4, arg)
      if (len_trim(arg) > 0) read(arg, *) se_rowtiny
      call se_load(dir, stat)
      n = se_n
      allocate(x(n), f(n), z(n), mz(n), s(n))
      x = 0d0
      jfnk_x = x
      se_ridge = eps
      jfnk_ptc_active = .false.
      call se_f_raw(n, x, f)
      call se_factor_lu()
      z = f
      call se_psolve_lsq(n, z)
      s = f
      call se_psolve_lsq2(n, s)
      mz = z - s
      write(*, '(A,ES24.16)') 'ZNORM ', sqrt(sum(z*z))
      write(*, '(A,ES24.16)') 'RELDIFF ', sqrt(sum(mz*mz)) / &
         max(sqrt(sum(z*z)), 1d-300)
      do i = 1, n
         write(*, '(A,I0,1X,2(ES24.16,1X))') 'Z ', i, z(i), s(i)
      end do

   case ('sereach')
      ! Reachability precheck (production admission diagnostic): apply
      ! the full production PC pipeline to F, then measure the fraction
      ! of F that the resulting step direction reaches via the stored
      ! BA block, reach = (2<F,Jz>-|Jz|^2)/|F|^2.  reach ~ 0 means the
      ! residual is left-null dominated and Newton cannot move it.
      call get_command_argument(2, dir)
      call get_command_argument(3, arg); read(arg, *) pc
      call get_command_argument(4, arg); read(arg, *) ridge
      call get_command_argument(5, arg); read(arg, *) rowtiny
      call se_load(dir, stat)
      n = se_n
      allocate(x(n), f(n), z(n), mz(n), s(n))
      x = 0d0
      jfnk_x = x
      se_ridge = ridge
      se_rowtiny = rowtiny
      se_expneg = .true.
      se_ptcfix = .true.
      jfnk_ptc_active = .true.
      call se_f_raw(n, x, f)
      call se_arm_ptc(n, f)
      if (pc == 7) then
         call se_factor_schur()
      else
         call se_factor_lu()
      end if
      z = f
      select case (pc)
      case (5)
         call se_psolve_lsq(n, z)
      case (6)
         call se_psolve_lsq2(n, z)
      case (7)
         call se_psolve_schur(n, z)
      case (1)
         call se_psolve_jacobi(n, z)
      case default
         call se_psolve(n, z)
      end select
      ! Jz through the raw per-depth BA blocks (m0_blk)
      mz = 0d0
      do k = 1, se_nd
         mz((k-1)*se_nt+1:k*se_nt) = matmul(m0_blk(:,:,k), &
              z((k-1)*se_nt+1:k*se_nt))
      end do
      do i = 1, n
         if (mask_se(i) == 1) then
            mz(i) = 0d0
         end if
      end do
      write(*, '(A,ES24.16)') 'FNORM  ', sqrt(sum(f*f))
      write(*, '(A,ES24.16)') 'ZNORM  ', sqrt(sum(z*z))
      write(*, '(A,ES24.16)') 'ZINF   ', maxval(abs(z))
      write(*, '(A,ES24.16)') 'JZNORM ', sqrt(sum(mz*mz))
      write(*, '(A,ES24.16)') 'MZIPV  ', sum(f*mz)
      write(*, '(A,ES24.16)') 'MZDIFF ', &
         sqrt(sum((mz-f)**2)) / max(sqrt(sum(f*f)), 1d-300)
      write(*, '(A,ES24.16)') 'REACH  ', &
         (2d0*sum(f*mz) - sum(mz*mz)) / max(sum(f*f), 1d-300)

   case ('segmres')
      call get_command_argument(2, dir)
      call get_command_argument(3, arg); read(arg, *) m
      call get_command_argument(4, arg); read(arg, *) itmax
      call get_command_argument(5, arg); read(arg, *) pc
      call get_command_argument(6, arg); read(arg, *) eps
      call get_command_argument(7, arg); read(arg, *) expneg
      call get_command_argument(8, arg); read(arg, *) ptc
      call get_command_argument(9, arg); read(arg, *) ptcfix
      ridge = 0d0
      call get_command_argument(10, arg)
      if (len_trim(arg) > 0) read(arg, *) ridge
      ! arg12: tauto mode 0=off 1=live-T unscaled-PC 2=PC-scaled
      ! (JFNK_TAUTO_SCALE_V1 analogue); arg13 = alpha.  Parsed before
      ! the baseline F/PC so the T rows are live from the start.
      call get_command_argument(12, arg)
      if (len_trim(arg) > 0) then
         read(arg, *) its
         se_tauto_on = (its > 0)
         se_tau_pcw = (its == 2)
         call get_command_argument(13, arg)
         if (len_trim(arg) > 0) then
            read(arg, *) gtmp
            se_tau_alpha = gtmp
         end if
      end if
      call se_load(dir, stat)
      n = se_n
      allocate(x(n), f(n), h(m+1,m), vv(n,m+1))
      x = 0d0
      jfnk_x = x
      jfnk_ptc_active = (ptc == 1)
      se_expneg = (expneg == 1)
      se_ptcfix = (ptcfix == 1)
      se_eps = eps
      se_ridge = ridge
      call se_f_raw(n, x, f)
      if (jfnk_ptc_active) call se_arm_ptc(n, f)
      if (pc == 7) then
         call se_factor_schur()
      else
         call se_factor_lu()
      end if
      f = -f   ! gmres solves J s = -F for the Newton correction
      do k = 1, itmax
         x = 0d0
         its = k
         info = 0
         res = 1d-14
         h = 0d0
         vv = 0d0
         jfnk_use_left_pc = .true.
         call get_command_argument(11, arg)
         if (len_trim(arg) > 0) then
            read(arg, *) info
            jfnk_use_left_pc = (info == 1)
         end if
         del = 0d0
         select case (pc)
         case (0)
            call gmres_m_v1(m, n, x, f, se_jvp_fd, se_psolve_ident, &
                 se_dp, h, vv, res, del, pred_res, its, info, 6)
         case (1)
            call gmres_m_v1(m, n, x, f, se_jvp_fd, se_psolve_jacobi, &
                 se_dp, h, vv, res, del, pred_res, its, info, 6)
         case (3)
            call gmres_m_v1(m, n, x, f, se_jvp_fd, se_psolve_tsvd, &
                 se_dp, h, vv, res, del, pred_res, its, info, 6)
         case (4)
            call gmres_m_v1(m, n, x, f, se_jvp_fd, se_psolve_ptclu, &
                 se_dp, h, vv, res, del, pred_res, its, info, 6)
         case (5)
            call gmres_m_v1(m, n, x, f, se_jvp_fd, se_psolve_lsq, &
                 se_dp, h, vv, res, del, pred_res, its, info, 6)
         case (6)
            call gmres_m_v1(m, n, x, f, se_jvp_fd, se_psolve_lsq2, &
                 se_dp, h, vv, res, del, pred_res, its, info, 6)
         case (7)
            call gmres_m_v1(m, n, x, f, se_jvp_fd, se_psolve_schur, &
                 se_dp, h, vv, res, del, pred_res, its, info, 6)
         case default
            call gmres_m_v1(m, n, x, f, se_jvp_fd, se_psolve, &
                 se_dp, h, vv, res, del, pred_res, its, info, 6)
         end select
         write(*, '(I0,1X,I0,2(1X,ES24.16),1X,I0)') &
            k, its, res, maxval(abs(x)), info
      end do

   case ('senewton')
      call get_command_argument(2, dir)
      call get_command_argument(3, arg); read(arg, *) m
      call get_command_argument(4, arg); read(arg, *) nits
      call get_command_argument(5, arg); read(arg, *) pc
      call get_command_argument(6, arg); read(arg, *) eps
      call get_command_argument(7, arg); read(arg, *) rowtiny
      call get_command_argument(8, arg); read(arg, *) ridge
      call get_command_argument(9, arg); read(arg, *) expneg
      call get_command_argument(10, arg); read(arg, *) ptc
      call get_command_argument(11, arg); read(arg, *) ptcfix
      call get_command_argument(12, arg); read(arg, *) eqscale
      call get_command_argument(13, arg); read(arg, *) cap
      call get_command_argument(14, arg); read(arg, *) gtolfac
      se_eqscale = (eqscale == 1)
      se_wscale_on = .false.
      call get_command_argument(17, arg)
      if (len_trim(arg) > 0) then
         read(arg, *) stat
         se_wscale_on = (stat == 1)
      end if
      call se_load(dir, stat)
      n = se_n
      allocate(x(n), f(n))
      se_rowtiny = rowtiny
      se_ridge = ridge
      se_expneg = (expneg == 1)
      se_ptcfix = (ptcfix == 1)
      se_eps = eps
      jfnk_step_inf_cap = cap
      jfnk_ptc_active = (ptc == 1)
      jfnk_log_unknown = .true.
      jfnk_use_left_pc = .true.
      jfnk_x = 0d0
      call se_f_raw(n, jfnk_x, f)
      if (jfnk_ptc_active) call se_arm_ptc(n, f)
      if (pc == 7) then
         call se_factor_schur()
      else
         call se_factor_lu()
      end if
      f0nrm = sqrt(se_dp(n, f, f))   ! same metric the solver sees
      ! production: tol = |F0|*1D-4 absolute target; del=-1 -> |F|/10
      tol = f0nrm * gtolfac
      gtol = 1d-3
      del = -1d0
      mndl = 1d-8
      mxdl = 1d2
      info = 0   ! quiet: keep stdout parseable
      call get_command_argument(15, arg)
      if (len_trim(arg) > 0) read(arg, *) info
      jfnk_use_left_pc = .true.
      call get_command_argument(16, arg)
      if (len_trim(arg) > 0) then
         read(arg, *) stat
         jfnk_use_left_pc = (stat == 1)
      end if
      ! REACH gate (arg18): replica of the production admission
      ! precheck in JFNK_SOLVE_CORR_V1 -- z = M^-1 F, Jz = BA z,
      ! REACH = (2<F,Jz>-<Jz,Jz>)/<F,F>; skip Newton when below gate.
      reach_ok = .true.
      call get_command_argument(18, arg)
      if (len_trim(arg) > 0) then
         read(arg, *) gtmp
         if (gtmp > 0d0 .and. (pc == 2 .or. pc >= 5)) then
            allocate(z(n), mz(n))
            z = f
            select case (pc)
            case (5)
               call se_psolve_lsq(n, z)
            case (6)
               call se_psolve_lsq2(n, z)
            case (7)
               call se_psolve_schur(n, z)
            case default
               call se_psolve(n, z)
            end select
            mz = 0d0
            do k = 1, se_nd
               mz((k-1)*se_nt+1:k*se_nt) = matmul(m0_blk(:,:,k), &
                    z((k-1)*se_nt+1:k*se_nt))
            end do
            rr = (2d0*se_dp(n,f,mz) - se_dp(n,mz,mz)) / &
                 max(se_dp(n,f,f), 1d-300)
            write(*, '(A,ES24.16)') 'REACH ', rr
            if (rr < gtmp) reach_ok = .false.
            deallocate(z, mz)
         end if
      end if
      if (reach_ok) then
      select case (pc)
      case (0)
         call newton_hook_v1(se_f, se_jvp_fd, se_psolve_ident, se_sub, &
              se_dp, m, n, gtol, tol, del, mndl, mxdl, nits, info, 6)
      case (1)
         call newton_hook_v1(se_f, se_jvp_fd, se_psolve_jacobi, se_sub, &
              se_dp, m, n, gtol, tol, del, mndl, mxdl, nits, info, 6)
      case (3)
         call newton_hook_v1(se_f, se_jvp_fd, se_psolve_tsvd, se_sub, &
              se_dp, m, n, gtol, tol, del, mndl, mxdl, nits, info, 6)
      case (4)
         call newton_hook_v1(se_f, se_jvp_fd, se_psolve_ptclu, se_sub, &
              se_dp, m, n, gtol, tol, del, mndl, mxdl, nits, info, 6)
      case (5)
         call newton_hook_v1(se_f, se_jvp_fd, se_psolve_lsq, se_sub, &
              se_dp, m, n, gtol, tol, del, mndl, mxdl, nits, info, 6)
      case (6)
         call newton_hook_v1(se_f, se_jvp_fd, se_psolve_lsq2, se_sub, &
              se_dp, m, n, gtol, tol, del, mndl, mxdl, nits, info, 6)
      case (7)
         call newton_hook_v1(se_f, se_jvp_fd, se_psolve_schur, se_sub, &
              se_dp, m, n, gtol, tol, del, mndl, mxdl, nits, info, 6)
      case default
         call newton_hook_v1(se_f, se_jvp_fd, se_psolve, se_sub, &
              se_dp, m, n, gtol, tol, del, mndl, mxdl, nits, info, 6)
      end select
      else
         write(*, '(A)') 'SKIPPED reach gate'
         info = -2
      end if
  900 continue
      write(*, '(A,I0)') 'INFO ', info
      write(*, '(A,ES24.16)') 'FNORM0 ', f0nrm
      write(*, '(A,ES24.16)') 'FNORM1 ', sqrt(sum(jfnk_fx*jfnk_fx))
      write(*, '(A,ES24.16)') 'TARGET ', tol
      write(*, '(A,I0)') 'NITS ', jfnk_nits
      write(*, '(A,I0)') 'FEVALS ', jfnk_total_f_evals
      write(*, '(A,I0)') 'JVEVALS ', jfnk_total_jvp_evals
      write(*, '(A)') 'X'
      do i = 1, n
         write(*, '(ES24.16)') jfnk_x(i)
      end do

   case ('sestrike')
      ! Strike/cooldown FSM replica of JFNK_SOLVE_CORR_V1 (the
      ! production counters JFNK_STAGNATION_COUNT / JFNK_DISABLED /
      ! JFNK_REARM_COUNT / JFNK_REARM_CYCLE live in the outer routine
      ! and cannot be driven from this unit driver).  Each character
      ! of <seq> is one admitted call: 'F' runs newton_hook_v1 with
      ! the production LU path (info=3 on these systems -> strike),
      ! 'S' runs LSQ-alg (info=0 on hard -> commit/reset), 'R' is the
      ! reach-gate skip (info=-2 -> Lambda fallback, not counted).
      ! PAUSE lines are the cooldown calls that take the Lambda step
      ! instead of Newton; REARM is the re-arm transition.
      call get_command_argument(2, dir)
      call get_command_argument(3, arg); read(arg, *) rearm_every
      call get_command_argument(4, seqstr)
      call se_load(dir, stat)
      if (stat /= 0) stop 2
      n = se_n
      stag = 0
      cool = 0
      cyc = 0
      disarm = .false.
      do i = 1, len_trim(seqstr)
         ! entry gating: count the skipped call, then compare against
         ! the adaptive wait (production order in JFNK_SOLVE_CORR_V1)
         if (disarm) cool = cool + 1
         wait_i = rearm_every * 2**min(cyc, 3)
         if (disarm .and. cool >= wait_i) then
            disarm = .false.
            stag = 0
            cool = 0
            write(*, '(A,I0,A,I0)') 'REARM ', i, ' after ', wait_i
         end if
         if (disarm) then
            write(*, '(A,I0,A,I0,A,I0)') 'PAUSE ', i, ' cooldown ', &
               cool, ' of ', wait_i
            cycle
         end if
         select case (seqstr(i:i))
         case ('R')
            info = -2
         case ('S')
            call se_run_newton(6, 1d-2, 0, info, 0)
         case default
            call se_run_newton(2, 0d0, 1, info, 0)
         end select
         ! outcome bookkeeping: committed update resets strike count
         ! and the backoff cycle; info=-2 is exempt; every other
         ! failed solve strikes, and JFNK_MAX_STAGNATE=3 pauses with
         ! the cycle counter doubling the next wait
         if (info == 0) then
            stag = 0
            cyc = 0
         else if (info == -2) then
            continue
         else
            stag = stag + 1
            if (stag >= 3) then
               disarm = .true.
               stag = 0
               cyc = cyc + 1
            end if
         end if
         write(*, '(A,I0,A,I0,A,I0,A,L1,A,I0)') 'ADM ', i, ' INFO ', &
            info, ' STAG ', stag, ' DIS ', disarm, ' CYCLE ', cyc
      end do

   case ('setauto')
      ! FIX_T_AUTO admission replica of JFNK_SOLVE_CORR_V1.  Each
      ! character of <seq> is one admission:
      !   'D' = damped-tauto admission: T rows live in F/JVP (the
      !         JVP keeps the true dF/dT subspace), PC T output scaled
      !         by the rung alpha (JFNK_TAU_PCW analogue), and the
      !         production jfnk_tauto_damp_v1 inside newton_hook_v1
      !         scales+caps every accepted step's T components;
      !   'F' = masked-T admission (the pre-existing hard-mask path);
      !   'R' = reach-gate skip (info=-2, no Newton);
      !   'p'/'P' = outer-iteration T perturbation of -0.05 / -1.0 on
      !         all T rows (production's Lambda/grey-T loop moves T
      !         between admissions); 'p' recreates a small RE deficit
      !         that a committing admission recovers gently, 'P' a
      !         re-shock that should trigger a rung revert.
      ! The ladder FSM mirrors production exactly: RE is the T-row
      ! residual norm measured on the admission baseline, RE0 anchors
      ! on its first nonzero value, info==0 increments the commit
      ! streak, a committed |dx_T|_inf above eps reverts a rung, and
      ! nlock commits with RE <= rel*RE0 release the next rung.
      ! State persists across admissions via keepx (the committed
      ! baseline carries like POPS does in production).
      call get_command_argument(2, dir)
      call get_command_argument(3, seqstr)
      call get_command_argument(4, arg); read(arg, *) vals(1)   ! a0
      call get_command_argument(5, arg); read(arg, *) vals(2)   ! rel
      call get_command_argument(6, arg); read(arg, *) vals(3)   ! eps
      call get_command_argument(7, arg); read(arg, *) vals(4)   ! dmax
      call get_command_argument(8, arg); read(arg, *) ta_nlock
      pc = 6
      call get_command_argument(9, arg)
      if (len_trim(arg) > 0) read(arg, *) pc
      call se_load(dir, stat)
      if (stat /= 0) stop 2
      n = se_n
      if (allocated(x)) deallocate(x)
      if (allocated(f)) deallocate(f)
      allocate(x(n), f(n))
      jfnk_x = 0d0
      rung = 1
      ncom = 0
      re0 = 0d0
      alpha_l = vals(1)
      se_tauto_on = .false.
      jfnk_tauto_on = .false.
      do i = 1, len_trim(seqstr)
         x = jfnk_x
         if (seqstr(i:i) == 'p' .or. seqstr(i:i) == 'P') then
            pert = -0.05d0
            if (seqstr(i:i) == 'P') pert = -1.0d0
            do k = 1, se_nd
               jfnk_x((k-1)*se_nt + se_trow) = &
                  jfnk_x((k-1)*se_nt + se_trow) + pert
            end do
            write(*, '(A,I0,A,ES10.3)') 'PERT ', i, ' dx_T=', pert
            cycle
         end if
         ! RE on the admission baseline: production measures it on
         ! jfnk_fx under JFNK_TAUTO_ACTIVE, which is set for 'D' and
         ! reach-skipped 'R' admissions alike, so both see live T
         ! rows here.  'F' admissions keep T masked (RE=0).
         se_tauto_on = (seqstr(i:i) /= 'F')
         call se_f_raw(n, jfnk_x, f)
         re_n = 0d0
         do k = 1, se_nd
            idx = (k-1)*se_nt + se_trow
            re_n = re_n + f(idx)**2
         end do
         re_n = sqrt(re_n)
         if (seqstr(i:i) /= 'F') then
            if (re0 <= 0d0 .and. re_n > 0d0) re0 = re_n
         end if
         select case (seqstr(i:i))
         case ('D')
            se_tauto_on = .true.
            se_tau_alpha = alpha_l
            jfnk_tauto_on = .true.
            jfnk_tauto_alpha = alpha_l
            jfnk_tauto_dmax = vals(4)
            jfnk_tauto_nt = se_nt
            jfnk_tauto_jt = se_trow
            jfnk_tauto_dst = 1
            jfnk_tauto_dend = se_nd
            call se_run_newton(pc, 1d-2, 0, info, 1)
         case ('F')
            se_tauto_on = .false.
            jfnk_tauto_on = .false.
            call se_run_newton(pc, 1d-2, 0, info, 1)
         case default
            info = -2
         end select
         ! committed log-T step this admission
         eps_t = 0d0
         do k = 1, se_nd
            idx = (k-1)*se_nt + se_trow
            eps_t = max(eps_t, abs(jfnk_x(idx) - x(idx)))
         end do
         ! ladder update only on damped-mode admissions (production
         ! runs the transition only under JFNK_TAUTO_ACTIVE)
         if (seqstr(i:i) /= 'F') then
            ! info=2 is the committed best-iterate (production
            ! COMMITTED_BASELINE), so it counts like a clean solve.
            if (info == 0 .or. info == 2) ncom = ncom + 1
            if (eps_t > vals(3)) then
               if (rung > 1) then
                  rung = rung - 1
                  ncom = 0
                  write(*, '(A,I0,A,ES10.3,A,I0)') 'REVERT ', i, &
                     ' eps=', eps_t, ' rung=', rung
               end if
            else if (ncom >= ta_nlock .and. re_n <= vals(2)*re0 &
                     .and. rung < 4) then
               rung = rung + 1
               ncom = 0
               write(*, '(A,I0,A,ES10.3,A,I0)') 'RELEASE ', i, &
                  ' re/re0=', re_n/max(re0, 1d-30), ' rung=', rung
            end if
            select case (rung)
            case (1)
               alpha_l = vals(1)
            case (2)
               alpha_l = 0.2d0
            case (3)
               alpha_l = 0.5d0
            case default
               alpha_l = 1.0d0
            end select
            jfnk_tauto_alpha = alpha_l
            se_tau_alpha = alpha_l
         end if
         write(*, '(A,I0,A,I0,A,ES10.3,A,ES10.3,A,ES10.3,A,I0,A,' // &
            'ES10.3,A,I0,A,ES10.3)') 'AUTO ', i, ' INFO ', info, &
            ' RE ', re_n, ' RE0 ', re0, ' EPS ', eps_t, ' RUNG ', &
            rung, ' ALPHA ', alpha_l, ' NC ', ncom, ' XT ', &
            maxval(abs(jfnk_x(se_trow::se_nt)))
         ! Invariant-2 probe: the residual the solver stored at the
         ! committed state (jfnk_fx) vs a fresh eval at the same x.
         ! They must be bit-identical -- a damped step still triggers a
         ! full F(x_new) evaluation, never a linearized reuse.
         call se_f_raw(n, jfnk_x, f)
         write(*, '(A,I0,A,ES24.16,A,ES24.16)') 'FCHK ', i, &
            ' STORED ', sqrt(sum(jfnk_fx*jfnk_fx)), &
            ' FRESH ', sqrt(sum(f*f))
         write(*, '(A,I0,A,99(ES24.16,1X))') 'XTALL ', i, ' ', &
            (jfnk_x((k-1)*se_nt + se_trow), k = 1, se_nd)
      end do
      se_tauto_on = .false.
      jfnk_tauto_on = .false.

   case ('sedamp')
      ! Invariant-6 probe: apply the production jfnk_tauto_damp_v1 to a
      ! vector of all ones and print the indices it changed.  Args:
      ! sedamp <dir> <alpha> <dmax> <dst> <dend>
      call get_command_argument(2, dir)
      call se_load(dir, stat)
      n = se_n
      allocate(x(n))
      call get_command_argument(3, arg); read(arg, *) gtmp
      call get_command_argument(4, arg); read(arg, *) pert
      jfnk_tauto_on = .true.
      jfnk_tauto_alpha = gtmp
      jfnk_tauto_dmax = pert
      jfnk_tauto_nt = se_nt
      jfnk_tauto_jt = se_trow
      call get_command_argument(5, arg); read(arg, *) jfnk_tauto_dst
      call get_command_argument(6, arg); read(arg, *) jfnk_tauto_dend
      x = 1d0
      call jfnk_tauto_damp_v1(n, x)
      do i = 1, n
         if (x(i) /= 1d0) write(*, '(A,I0,A,ES24.16)') &
            'DAMPED ', i, ' -> ', x(i)
      end do
      jfnk_tauto_on = .false.

   case default
      write(*, '(A)') 'unknown command: ' // trim(cmd)
      stop 64
   end select

contains

   subroutine se_run_newton(pc_in, rgv, exn, inf, keepx)
      ! One admission of the surrogate Newton solve, configured the
      ! way t6 runs senewton: fresh x=0 baseline, PTC armed on F(0),
      ! per-depth factor, then newton_hook_v1 with production args.
      ! keepx=1 keeps jfnk_x (the committed baseline carries across
      ! admissions, like POPS does in production) and re-anchors the
      ! PTC term at the current x instead of 0.
      implicit none
      integer, intent(in) :: pc_in, exn, keepx
      double precision, intent(in) :: rgv
      integer, intent(out) :: inf
      double precision, allocatable :: fx0(:)
      double precision :: f0n, tol_l, del_l, mndl_l, mxdl_l, gtol_l
      integer :: nits_l, m_l, info_l
      info_l = 0
      se_rowtiny = 1d-30
      se_ridge = rgv
      se_expneg = (exn == 1)
      se_ptcfix = .true.
      se_eps = 1d-2
      se_eqscale = .false.
      se_wscale_on = .false.
      jfnk_step_inf_cap = 10d0
      jfnk_ptc_active = .true.
      jfnk_log_unknown = .true.
      jfnk_use_left_pc = .true.
      if (keepx == 0) jfnk_x = 0d0
      allocate(fx0(se_n))
      call se_f_raw(se_n, jfnk_x, fx0)
      call se_arm_ptc(se_n, fx0)
      if (keepx /= 0) jfnk_ptc_x0 = jfnk_x
      if (pc_in == 7) then
         call se_factor_schur()
      else
         call se_factor_lu()
      end if
      f0n = sqrt(se_dp(se_n, fx0, fx0))
      tol_l = f0n * 1d-4
      gtol_l = 1d-3
      del_l = -1d0
      mndl_l = 1d-8
      mxdl_l = 1d2
      nits_l = 30
      m_l = 20
      select case (pc_in)
      case (6)
         call newton_hook_v1(se_f, se_jvp_fd, se_psolve_lsq2, se_sub, &
              se_dp, m_l, se_n, gtol_l, tol_l, del_l, mndl_l, mxdl_l, &
              nits_l, info_l, 6)
      case (7)
         call newton_hook_v1(se_f, se_jvp_fd, se_psolve_schur, se_sub, &
              se_dp, m_l, se_n, gtol_l, tol_l, del_l, mndl_l, mxdl_l, &
              nits_l, info_l, 6)
      case default
         call newton_hook_v1(se_f, se_jvp_fd, se_psolve, se_sub, &
              se_dp, m_l, se_n, gtol_l, tol_l, del_l, mndl_l, mxdl_l, &
              nits_l, info_l, 6)
      end select
      inf = info_l
      deallocate(fx0)
   end subroutine se_run_newton

   subroutine se_arm_ptc(nn, f0)
      ! production JFNK_SET_PTC_SCALE_V1: scale_i = max(|F0_i|, floor)
      implicit none
      integer, intent(in) :: nn
      double precision, intent(in) :: f0(nn)
      double precision :: fmax
      if (allocated(jfnk_ptc_scale)) deallocate(jfnk_ptc_scale)
      if (allocated(jfnk_ptc_x0)) deallocate(jfnk_ptc_x0)
      allocate(jfnk_ptc_scale(nn), jfnk_ptc_x0(nn))
      fmax = maxval(abs(f0))
      jfnk_ptc_scale = max(abs(f0), max(1d-30, 1d-8*fmax))
      jfnk_ptc_x0 = 0d0
      jfnk_ptc_scale_ready = .true.
      jfnk_ptc_anchor_ready = .true.
      jfnk_ptc_dtau = 1d0
   end subroutine se_arm_ptc

end program se_driver
