      PROGRAM DRV_SOB_PROF
      USE SET_KIND_MODULE
      IMPLICIT NONE

      INTEGER, PARAMETER :: ND=4
      INTEGER, PARAMETER :: NCF=81
      INTEGER, PARAMETER :: MAX_SIM=3
      INTEGER, PARAMETER :: N_LINES=3
      INTEGER, PARAMETER :: LU_ETA=21
      INTEGER, PARAMETER :: LU_CHI=22
      INTEGER, PARAMETER :: LU_DIAG=23

      REAL(KIND=LDP) :: ETA_ST(ND,NCF)
      REAL(KIND=LDP) :: CHI_ST(ND,NCF)
      REAL(KIND=LDP) :: NU(NCF)
      REAL(KIND=LDP) :: CHIL_MAT(ND,MAX_SIM)
      REAL(KIND=LDP) :: ETAL_MAT(ND,MAX_SIM)
      REAL(KIND=LDP) :: CLUMP_FAC(ND)
      REAL(KIND=LDP) :: FL_SIM(MAX_SIM)
      REAL(KIND=LDP) :: VDOP_MIN(N_LINES)
      REAL(KIND=LDP) :: ARAD_VEC(N_LINES)
      REAL(KIND=LDP) :: C4_VEC(N_LINES)
      REAL(KIND=LDP) :: ED_IN(ND)
      REAL(KIND=LDP) :: C_KMS
      REAL(KIND=LDP) :: DROP_SUM
      REAL(KIND=LDP) :: INJ_SUM
      REAL(KIND=LDP) :: PI
      INTEGER :: SIM_POINTER(MAX_SIM)
      INTEGER :: N_DROP
      INTEGER :: I
      INTEGER :: K
      INTEGER :: MODE
      LOGICAL :: NEG_OPACITY(ND)
      CHARACTER(LEN=8) :: TRANS_TYPE(N_LINES)
      CHARACTER(LEN=16) :: MODE_STR
      CHARACTER(LEN=256) :: OUT_DIR

      CALL GET_COMMAND_ARGUMENT(1,OUT_DIR)
      MODE_STR=' '
      CALL GET_COMMAND_ARGUMENT(2,MODE_STR)
      MODE=0
      IF(LEN_TRIM(MODE_STR) .GT. 0)READ(MODE_STR,*)MODE
      IF(LEN_TRIM(OUT_DIR) .EQ. 0)THEN
        WRITE(*,*)'usage: drv_sob_prof OUT_DIR [MODE]'
        STOP 1
      END IF

      PI=ACOS(-1.0_LDP)
      DO K=1,NCF
        NU(K)=0.50035_LDP-0.0007_LDP*REAL(K-1,LDP)/REAL(NCF-1,LDP)
        NU(K)=NU(K)+2.0E-7_LDP*
     1        SIN(2.0_LDP*PI*REAL(K-1,LDP)/REAL(NCF-1,LDP))
      END DO

      ETA_ST=0.0_LDP
      CHI_ST=0.0_LDP
      CHIL_MAT=0.0_LDP
      ETAL_MAT=0.0_LDP
      CLUMP_FAC(1)=1.0_LDP
      CLUMP_FAC(2)=2.0_LDP
      CLUMP_FAC(3)=0.5_LDP
      CLUMP_FAC(4)=1.5_LDP
      NEG_OPACITY(1)=.FALSE.
      NEG_OPACITY(2)=.FALSE.
      NEG_OPACITY(3)=.FALSE.
      NEG_OPACITY(4)=.TRUE.

      CHIL_MAT(1,1)=2.0E-4_LDP
      CHIL_MAT(2,1)=3.0E-4_LDP
      CHIL_MAT(3,1)=-1.0E-4_LDP
      CHIL_MAT(4,1)=4.0E-4_LDP
      ETAL_MAT(1,1)=0.2_LDP
      ETAL_MAT(2,1)=0.3_LDP
      ETAL_MAT(3,1)=0.4_LDP
      ETAL_MAT(4,1)=0.5_LDP
      CHIL_MAT(:,2)=9.0E-4_LDP
      ETAL_MAT(:,2)=9.0_LDP
      CHIL_MAT(:,3)=7.0E-4_LDP
      ETAL_MAT(:,3)=7.0_LDP

      FL_SIM(1)=0.5_LDP
      FL_SIM(2)=0.6_LDP
      FL_SIM(3)=0.4998_LDP
      SIM_POINTER(1)=1
      SIM_POINTER(2)=2
      SIM_POINTER(3)=3
      VDOP_MIN(1)=50.0_LDP
      VDOP_MIN(2)=50.0_LDP
      VDOP_MIN(3)=50.0_LDP
      TRANS_TYPE(1)='SOB'
      TRANS_TYPE(2)='SOB'
      TRANS_TYPE(3)='BLANK'
      IF(MODE .EQ. 1)TRANS_TYPE(:)='BLANK'
      ARAD_VEC=0.0_LDP
      C4_VEC=0.0_LDP
      ED_IN=0.0_LDP
      C_KMS=299792.458_LDP
      N_DROP=0
      DROP_SUM=0.0_LDP
      INJ_SUM=0.0_LDP

      CALL ADD_SOB_LINE_PROF(ETA_ST,CHI_ST,NU,NCF,
     1     CHIL_MAT,ETAL_MAT,CLUMP_FAC,FL_SIM,SIM_POINTER,
     2     VDOP_MIN,ARAD_VEC,C4_VEC,ED_IN,
     3     TRANS_TYPE,NEG_OPACITY,
     4     MAX_SIM,N_LINES,MAX_SIM,ND,C_KMS,
     5     N_DROP,DROP_SUM,INJ_SUM)

      OPEN(UNIT=LU_ETA,FILE=TRIM(OUT_DIR)//'/eta_out.txt',
     1     STATUS='REPLACE')
      OPEN(UNIT=LU_CHI,FILE=TRIM(OUT_DIR)//'/chi_out.txt',
     1     STATUS='REPLACE')
      DO I=1,ND
        WRITE(LU_ETA,'(81(ES25.17,1X))')ETA_ST(I,:)
        WRITE(LU_CHI,'(81(ES25.17,1X))')CHI_ST(I,:)
      END DO
      CLOSE(LU_ETA)
      CLOSE(LU_CHI)

      OPEN(UNIT=LU_DIAG,FILE=TRIM(OUT_DIR)//'/diag.txt',
     1     STATUS='REPLACE')
      WRITE(LU_DIAG,'(I8,2ES25.17)')N_DROP,DROP_SUM,INJ_SUM
      CLOSE(LU_DIAG)
      END

      INCLUDE 'ADD_SOB_LINE_PROF.INC'
