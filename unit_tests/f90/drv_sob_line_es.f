      PROGRAM DRV_SOB_LINE_ES
      USE SET_KIND_MODULE
      IMPLICIT NONE

      INTEGER, PARAMETER :: ND=4
      INTEGER, PARAMETER :: NCF=5
      INTEGER, PARAMETER :: NDEXT=6
      INTEGER, PARAMETER :: NCEXT=2
      INTEGER, PARAMETER :: NPEXT=8
      INTEGER, PARAMETER :: LU_ETA=21
      INTEGER, PARAMETER :: LU_RJ=22
      INTEGER, PARAMETER :: LU_RJES=23
      INTEGER, PARAMETER :: LU_DIAG=24
      INTEGER, PARAMETER :: LU_IB=25

      REAL(KIND=LDP) :: ETA_ST(ND,NCF)
      REAL(KIND=LDP) :: CHI_ST(ND,NCF)
      REAL(KIND=LDP) :: RJ_ST(ND,NCF)
      REAL(KIND=LDP) :: RJ_ES_ST(ND,NCF)
      REAL(KIND=LDP) :: IB_J_ST(NCF)
      REAL(KIND=LDP) :: IB_H_ST(NCF)
      REAL(KIND=LDP) :: RAY_ST(ND,NCF)
      REAL(KIND=LDP) :: DUST_ST(ND,NCF)
      REAL(KIND=LDP) :: ESEC(ND)
      REAL(KIND=LDP) :: CLUMP_FAC(ND)
      REAL(KIND=LDP) :: NU(NCF)
      REAL(KIND=LDP) :: T(ND)
      REAL(KIND=LDP) :: DTDR
      REAL(KIND=LDP) :: COEF(0:3,NDEXT)
      REAL(KIND=LDP) :: REXT(NDEXT)
      REAL(KIND=LDP) :: PEXT(NPEXT)
      REAL(KIND=LDP) :: VEXT(NDEXT)
      REAL(KIND=LDP) :: TEXT(NDEXT)
      REAL(KIND=LDP) :: SIGMAEXT(NDEXT)
      REAL(KIND=LDP) :: VDOP_VEC_EXT(NDEXT)
      REAL(KIND=LDP) :: AQWEXT(NDEXT,NPEXT)
      REAL(KIND=LDP) :: HQWEXT(NDEXT,NPEXT)
      REAL(KIND=LDP) :: KQWEXT(NDEXT,NPEXT)
      REAL(KIND=LDP) :: NQWEXT(NDEXT,NPEXT)
      REAL(KIND=LDP) :: HMIDQWEXT(NDEXT,NPEXT)
      REAL(KIND=LDP) :: NMIDQWEXT(NDEXT,NPEXT)
      REAL(KIND=LDP) :: MAX_CHG
      REAL(KIND=LDP) :: BASE_ETA(ND,NCF)
      INTEGER :: INDX(NDEXT)
      INTEGER :: POS_IN_NEW_GRID(ND)
      INTEGER :: I
      INTEGER :: K
      INTEGER :: MODE
      INTEGER :: NDEXT_USE
      INTEGER :: JMAP
      CHARACTER(LEN=16) :: MODE_STR
      CHARACTER(LEN=256) :: OUT_DIR

      COMMON/CONSTANTS/ CHIBF,CHIFF,HDKT,TWOHCSQ
      REAL(KIND=LDP) CHIBF,CHIFF,HDKT,TWOHCSQ
      COMMON/TESTMODE/ MODE
      COMMON/TESTBASE/ BASE_ETA

      CALL GET_COMMAND_ARGUMENT(1,OUT_DIR)
      MODE_STR=' '
      CALL GET_COMMAND_ARGUMENT(2,MODE_STR)
      MODE=0
      IF(LEN_TRIM(MODE_STR) .GT. 0)READ(MODE_STR,*)MODE
      IF(LEN_TRIM(OUT_DIR) .EQ. 0)THEN
        WRITE(*,*)'usage: drv_sob_line_es OUT_DIR MODE'
        STOP 1
      END IF

      CHIBF=0.0_LDP
      CHIFF=0.0_LDP
      HDKT=1.0_LDP
      TWOHCSQ=1.0_LDP
      T=1.0_LDP
      DTDR=0.5_LDP
      ESEC=0.1_LDP
      CLUMP_FAC=1.0_LDP
      COEF=0.0_LDP
      DO I=1,NDEXT
        INDX(I)=1
        JMAP=MIN(I-1,3)
        COEF(JMAP,I)=1.0_LDP
        REXT(I)=REAL(NDEXT-I+1,LDP)
        VEXT(I)=REAL(I,LDP)
        TEXT(I)=1.0_LDP
        SIGMAEXT(I)=0.0_LDP
        VDOP_VEC_EXT(I)=1.0_LDP
      END DO
      PEXT=0.5_LDP
      AQWEXT=1.0_LDP
      HQWEXT=1.0_LDP
      KQWEXT=1.0_LDP
      NQWEXT=1.0_LDP
      HMIDQWEXT=1.0_LDP
      NMIDQWEXT=1.0_LDP
      DO I=1,ND
        POS_IN_NEW_GRID(I)=I
      END DO

      DO K=1,NCF
        NU(K)=5.0_LDP-0.25_LDP*REAL(K-1,LDP)
        IB_J_ST(K)=3.0_LDP+0.001_LDP*ND
        IB_H_ST(K)=0.1_LDP
        DO I=1,ND
          BASE_ETA(I,K)=10.0_LDP+0.1_LDP*I+0.01_LDP*K
          CHI_ST(I,K)=2.0_LDP+0.01_LDP*I
          RJ_ST(I,K)=3.0_LDP+0.001_LDP*I
          RJ_ES_ST(I,K)=3.5_LDP+0.001_LDP*I+0.0001_LDP*K
          RAY_ST(I,K)=0.02_LDP+0.001_LDP*I
          DUST_ST(I,K)=0.03_LDP+0.001_LDP*I
          ETA_ST(I,K)=BASE_ETA(I,K)+ESEC(I)*RJ_ES_ST(I,K)+
     1        (RAY_ST(I,K)+DUST_ST(I,K))*RJ_ST(I,K)
        END DO
      END DO
      IF(MODE .EQ. 0)THEN
        RJ_ES_ST(:,:)=RJ_ST(:,:)
        DO K=1,NCF
          DO I=1,ND
            ETA_ST(I,K)=BASE_ETA(I,K)+ESEC(I)*RJ_ES_ST(I,K)+
     1          (RAY_ST(I,K)+DUST_ST(I,K))*RJ_ST(I,K)
          END DO
        END DO
      END IF
      NDEXT_USE=NDEXT
      IF(MODE .EQ. 3)NDEXT_USE=ND

      CALL SOB_LINE_ES_UPDATE(ETA_ST,CHI_ST,RJ_ST,RJ_ES_ST,
     1    IB_J_ST,IB_H_ST,RAY_ST,DUST_ST,ESEC,CLUMP_FAC,NU,T,DTDR,
     2    COEF,INDX,POS_IN_NEW_GRID,REXT,PEXT,VEXT,TEXT,SIGMAEXT,
     3    VDOP_VEC_EXT,AQWEXT,HQWEXT,KQWEXT,NQWEXT,HMIDQWEXT,
     4    NMIDQWEXT,ND,NCF,NDEXT_USE,NCEXT,NPEXT,2,
     5    .TRUE.,.TRUE.,MODE .EQ. 0,MODE .NE. 3,.TRUE.,.FALSE.,.FALSE.,
     6    0.0_LDP,.TRUE.,0.0_LDP,0.0_LDP,0.25_LDP,
     7    'ZERO','INT',6,4,MAX_CHG)

      OPEN(UNIT=LU_ETA,FILE=TRIM(OUT_DIR)//'/eta_es.txt',
     1     STATUS='REPLACE')
      OPEN(UNIT=LU_RJ,FILE=TRIM(OUT_DIR)//'/rj_es.txt',
     1     STATUS='REPLACE')
      OPEN(UNIT=LU_RJES,FILE=TRIM(OUT_DIR)//'/rj_es_conv.txt',
     1     STATUS='REPLACE')
      DO I=1,ND
        WRITE(LU_ETA,'(5(ES25.17,1X))')ETA_ST(I,:)
        WRITE(LU_RJ,'(5(ES25.17,1X))')RJ_ST(I,:)
        WRITE(LU_RJES,'(5(ES25.17,1X))')RJ_ES_ST(I,:)
      END DO
      CLOSE(LU_ETA)
      CLOSE(LU_RJ)
      CLOSE(LU_RJES)
      OPEN(UNIT=LU_DIAG,FILE=TRIM(OUT_DIR)//'/diag_es.txt',
     1     STATUS='REPLACE')
      WRITE(LU_DIAG,'(ES25.17)')MAX_CHG
      CLOSE(LU_DIAG)
      OPEN(UNIT=LU_IB,FILE=TRIM(OUT_DIR)//'/ib_out.txt',
     1     STATUS='REPLACE')
      WRITE(LU_IB,'(5(ES25.17,1X))')IB_J_ST
      WRITE(LU_IB,'(5(ES25.17,1X))')IB_H_ST
      CLOSE(LU_IB)
      END
