      SUBROUTINE FG_J_CMF_V12(ETA,CHI,ESEC,V,SIGMA,R,P,
     1            JNU,FEDD,JQW,HQW,KQW,NQW,HMIDQW,NMIDQW,
     2            RETURNED_IN_HBC,RETURNED_OUT_HBC,IPLUS_P,
     3            FREQ,dLOG_NU,DIF,DBB,IC,
     4            VDOP_VEC,VDOP_FRAC,REXT_FAC,
     5            METHOD,SOLUTION_OPTIONS,THK,INIT,NEW_FREQ,NC,NP,ND)
      USE SET_KIND_MODULE
      IMPLICIT NONE
      INTEGER NC,NP,ND
      REAL(KIND=LDP) ETA(ND),CHI(ND),ESEC(ND),V(ND),SIGMA(ND)
      REAL(KIND=LDP) R(ND),P(NP),JNU(ND),FEDD(ND),IPLUS_P(NP)
      REAL(KIND=LDP) JQW(ND,NP),HQW(ND,NP),KQW(ND,NP),NQW(ND,NP)
      REAL(KIND=LDP) HMIDQW(ND,NP),NMIDQW(ND,NP)
      REAL(KIND=LDP) RETURNED_IN_HBC,RETURNED_OUT_HBC
      REAL(KIND=LDP) FREQ,dLOG_NU,DBB,IC,VDOP_VEC(ND)
      REAL(KIND=LDP) VDOP_FRAC,REXT_FAC
      CHARACTER*6 METHOD,N_TYPE
      CHARACTER*10 SOLUTION_OPTIONS
      LOGICAL DIF,THK,INIT,NEW_FREQ
      INTEGER I,MODE
      COMMON/TESTMODE/ MODE
      IF(MODE .EQ. 0)THEN
        JNU(1:ND)=3.0_LDP+0.001_LDP*(/ (I,I=1,ND) /)
      ELSE IF(MODE .EQ. 1 .OR. MODE .EQ. 3)THEN
        JNU(1:ND)=4.0_LDP
      ELSE
        JNU(1:ND)=1.0_LDP+10.0_LDP*
     1      EXP(-((FREQ-4.0_LDP)/0.15_LDP)**2)
      END IF
      FEDD(1:ND)=JNU(1:ND)/3.0_LDP
      IPLUS_P(1:NP)=JNU(1)
      RETURNED_IN_HBC=0.0_LDP
      RETURNED_OUT_HBC=0.0_LDP
      RETURN
      END
