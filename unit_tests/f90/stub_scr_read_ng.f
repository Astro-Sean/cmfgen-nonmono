C Stub SCR_READ_V2 for NG_SHADOW_DIAG tests -- unlike the
C link-satisfaction stub, this one serves synthetic records
C loaded from a case file so DO_NG_BAND_ACCEL_V4 can exercise
C its multi-record read path. IREC_RD=0 returns the newest
C record index; out-of-range indices set NEWMOD, matching the
C production read-failure semantics.
C
	MODULE STUB_NG_MOD
	USE SET_KIND_MODULE
	IMPLICIT NONE
	INTEGER NREC_S,NT_S,ND_S,LSTNG_S
	REAL(KIND=LDP), ALLOCATABLE :: RECS(:,:,:)
	REAL(KIND=LDP), ALLOCATABLE :: RS(:),VS(:),SS(:)
	CONTAINS
	SUBROUTINE STUB_NG_LOAD(CFILE)
	CHARACTER(*) CFILE
	INTEGER I,K,L
	OPEN(55,FILE=CFILE,STATUS='OLD',ACTION='READ')
	READ(55,*)NT_S,ND_S,NREC_S,LSTNG_S
	ALLOCATE(RECS(NT_S,ND_S,NREC_S))
	ALLOCATE(RS(ND_S),VS(ND_S),SS(ND_S))
	READ(55,*)(RS(L),VS(L),SS(L),L=1,ND_S)
	DO I=1,NREC_S
	  DO L=1,ND_S
	    READ(55,*)(RECS(K,L,I),K=1,NT_S)
	  END DO
	END DO
	CLOSE(55)
	RETURN
	END
	END MODULE STUB_NG_MOD
C
	SUBROUTINE SCR_READ_V2(R,V,SIGMA,POPS,IREC,NITSF,
	1         NUM_TIMES,LST_NG,WRITE_RVSIG,NT,ND,LUSCR,NEWMOD)
	USE STUB_NG_MOD
	USE SET_KIND_MODULE
	IMPLICIT NONE
	INTEGER NT,ND,IREC,NITSF,NUM_TIMES,LST_NG,LUSCR
	REAL(KIND=LDP) R(ND),V(ND),SIGMA(ND),POPS(NT,ND)
	LOGICAL WRITE_RVSIG,NEWMOD
	INTEGER J,K,L
	NEWMOD=.FALSE.
	J=IREC
	IF(J.EQ.0)J=NREC_S
	IF(J.LT.1 .OR. J.GT.NREC_S)THEN
	  NEWMOD=.TRUE.
	  RETURN
	END IF
	IREC=J
	DO L=1,ND
	  R(L)=RS(L)
	  V(L)=VS(L)
	  SIGMA(L)=SS(L)
	  DO K=1,NT
	    POPS(K,L)=RECS(K,L,J)
	  END DO
	END DO
	NITSF=J
	LST_NG=LSTNG_S
	WRITE_RVSIG=.TRUE.
	RETURN
	END
