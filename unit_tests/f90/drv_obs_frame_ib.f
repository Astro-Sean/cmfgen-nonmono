      PROGRAM DRV_OBS_FRAME_IB
      USE SET_KIND_MODULE
      IMPLICIT NONE

      INTEGER, PARAMETER :: ND=5
      INTEGER, PARAMETER :: NCF=4
      INTEGER, PARAMETER :: NC=3
      INTEGER, PARAMETER :: NP=7
      INTEGER, PARAMETER :: NOS=2
      INTEGER, PARAMETER :: LU_OUT=21

      REAL(KIND=LDP) :: ETA_CMF(ND,NCF)
      REAL(KIND=LDP) :: CHI_CMF(ND,NCF)
      REAL(KIND=LDP) :: FREQ_CMF(NCF)
      REAL(KIND=LDP) :: R(ND)
      REAL(KIND=LDP) :: V(ND)
      REAL(KIND=LDP) :: T(ND)
      REAL(KIND=LDP) :: ED(ND)
      REAL(KIND=LDP) :: P(NP)
      REAL(KIND=LDP) :: MU_AT_RMAX(NP)
      REAL(KIND=LDP) :: HQW_AT_RMAX(NP)
      REAL(KIND=LDP) :: OBS_FREQ(NOS)
      REAL(KIND=LDP) :: OBS_FLUX(NOS)
      REAL(KIND=LDP) :: MAX_DEL_V_RES_ZONE(ND)
      REAL(KIND=LDP) :: TAU_MAX
      REAL(KIND=LDP) :: ES_DTAU
      REAL(KIND=LDP) :: TAU_REF
      REAL(KIND=LDP) :: IB_J_CMF(NCF)
      REAL(KIND=LDP) :: IB_H_CMF(NCF)
      INTEGER :: I
      INTEGER :: N_INS_OBS
      LOGICAL :: WRITE_RTAU
      LOGICAL :: WRITE_IP
      LOGICAL :: WRITE_DFR
      LOGICAL :: DO_REL
      LOGICAL :: PLANE_PARALLEL
      CHARACTER(LEN=256) :: OUT_DIR

      CALL GET_COMMAND_ARGUMENT(1,OUT_DIR)
      IF(LEN_TRIM(OUT_DIR) .EQ. 0)THEN
        WRITE(*,*)'usage: drv_obs_frame_ib OUT_DIR'
        STOP 1
      END IF

      R=(/10.0_LDP,8.0_LDP,6.0_LDP,4.0_LDP,2.0_LDP/)
      V=200.0_LDP
      T=1.0_LDP
      ED=1.0_LDP
      P=(/0.0_LDP,1.0_LDP,1.9_LDP,3.0_LDP,5.0_LDP,7.0_LDP,9.0_LDP/)
      MU_AT_RMAX=SQRT(1.0_LDP-(P/R(1))**2)
      HQW_AT_RMAX=1.0_LDP
      FREQ_CMF=(/5.0_LDP,4.5_LDP,4.0_LDP,3.5_LDP/)
      OBS_FREQ=(/4.45_LDP,4.05_LDP/)
      ETA_CMF=0.0_LDP
      CHI_CMF=1.0E-8_LDP
      MAX_DEL_V_RES_ZONE=50.0_LDP
      TAU_MAX=20.0_LDP
      ES_DTAU=1.0_LDP
      N_INS_OBS=1
      TAU_REF=1.0_LDP
      WRITE_RTAU=.FALSE.
      WRITE_IP=.FALSE.
      WRITE_DFR=.FALSE.
      DO_REL=.FALSE.
      PLANE_PARALLEL=.FALSE.
      IB_J_CMF=100.0_LDP
      IB_H_CMF=10.0_LDP

      OBS_FLUX=0.0_LDP
      CALL OBS_FRAME_SUB_V9(ETA_CMF,CHI_CMF,FREQ_CMF,
     1      R,V,T,ED,ND,NCF,P,MU_AT_RMAX,HQW_AT_RMAX,NC,NP,
     2      OBS_FREQ,OBS_FLUX,NOS,MAX_DEL_V_RES_ZONE,
     3      TAU_MAX,ES_DTAU,N_INS_OBS,'STAU',TAU_REF,
     4      WRITE_RTAU,WRITE_IP,WRITE_DFR,DO_REL,PLANE_PARALLEL,
     5      IB_J_CMF,IB_H_CMF,.FALSE.)
      OPEN(UNIT=LU_OUT,FILE=TRIM(OUT_DIR)//'/flux_no_ib.txt',
     1     STATUS='REPLACE')
      WRITE(LU_OUT,'(2(ES25.17,1X))')OBS_FLUX
      CLOSE(LU_OUT)

      OBS_FLUX=0.0_LDP
      CALL OBS_FRAME_SUB_V9(ETA_CMF,CHI_CMF,FREQ_CMF,
     1      R,V,T,ED,ND,NCF,P,MU_AT_RMAX,HQW_AT_RMAX,NC,NP,
     2      OBS_FREQ,OBS_FLUX,NOS,MAX_DEL_V_RES_ZONE,
     3      TAU_MAX,ES_DTAU,N_INS_OBS,'STAU',TAU_REF,
     4      WRITE_RTAU,WRITE_IP,WRITE_DFR,DO_REL,PLANE_PARALLEL,
     5      IB_J_CMF,IB_H_CMF,.TRUE.)
      OPEN(UNIT=LU_OUT,FILE=TRIM(OUT_DIR)//'/flux_ib.txt',
     1     STATUS='REPLACE')
      WRITE(LU_OUT,'(2(ES25.17,1X))')OBS_FLUX
      CLOSE(LU_OUT)

      IB_J_CMF=200.0_LDP
      IB_H_CMF=20.0_LDP
      OBS_FLUX=0.0_LDP
      CALL OBS_FRAME_SUB_V9(ETA_CMF,CHI_CMF,FREQ_CMF,
     1      R,V,T,ED,ND,NCF,P,MU_AT_RMAX,HQW_AT_RMAX,NC,NP,
     2      OBS_FREQ,OBS_FLUX,NOS,MAX_DEL_V_RES_ZONE,
     3      TAU_MAX,ES_DTAU,N_INS_OBS,'STAU',TAU_REF,
     4      WRITE_RTAU,WRITE_IP,WRITE_DFR,DO_REL,PLANE_PARALLEL,
     5      IB_J_CMF,IB_H_CMF,.TRUE.)
      OPEN(UNIT=LU_OUT,FILE=TRIM(OUT_DIR)//'/flux_ib2.txt',
     1     STATUS='REPLACE')
      WRITE(LU_OUT,'(2(ES25.17,1X))')OBS_FLUX
      CLOSE(LU_OUT)

      ETA_CMF=1.0E-6_LDP
      V=(/5000.0_LDP,1000.0_LDP,4500.0_LDP,500.0_LDP,
     1    2000.0_LDP/)
      MAX_DEL_V_RES_ZONE=20.0_LDP
      OBS_FLUX=0.0_LDP
      CALL OBS_FRAME_SUB_V9(ETA_CMF,CHI_CMF,FREQ_CMF,
     1      R,V,T,ED,ND,NCF,P,MU_AT_RMAX,HQW_AT_RMAX,NC,NP,
     2      OBS_FREQ,OBS_FLUX,NOS,MAX_DEL_V_RES_ZONE,
     3      TAU_MAX,ES_DTAU,N_INS_OBS,'STAU',TAU_REF,
     4      WRITE_RTAU,WRITE_IP,WRITE_DFR,DO_REL,PLANE_PARALLEL,
     5      IB_J_CMF,IB_H_CMF,.TRUE.)
      OPEN(UNIT=LU_OUT,FILE=TRIM(OUT_DIR)//'/flux_nonmono.txt',
     1     STATUS='REPLACE')
      WRITE(LU_OUT,'(2(ES25.17,1X))')OBS_FLUX
      CLOSE(LU_OUT)
      END
